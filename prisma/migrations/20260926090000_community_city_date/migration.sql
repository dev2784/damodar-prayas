 WHEN "category" = 'EVENT' THEN COALESCE("eventDate", "createdAt")
 WHEN "category" = 'OBITUARY' THEN COALESCE("eventDate", "deathDate", "createdAt")
 ELSE "createdAt" END) + INTERVAL '5 hours 30 minutes')::date;
